#!/usr/bin/env bash
# Copy to docs/learnings/reindex.sh in an onboarded project.
# Rebuild INDEX.md from learning frontmatter after every ledger change.
set -euo pipefail
cd "$(dirname "$0")"
{
  echo "# Learning index"
  echo
  echo 'Generated by `reindex.sh`—do not edit by hand.'
  echo
  echo "| id | learning | status | spec | PR | merged | file |"
  echo "|---|---|---|---|---|---|---|"
  for f in L[0-9][0-9][0-9]-*.md archive/L[0-9][0-9][0-9]-*.md; do
    [ -e "$f" ] || continue
    id=$(sed -n 's/^id: *\([^ #]*\).*/\1/p' "$f" | head -1)
    status=$(sed -n 's/^status: *\([^ #]*\).*/\1/p' "$f" | head -1)
    spec=$(sed -n 's/^spec: *\([^ #]*\).*/\1/p' "$f" | head -1)
    pr=$(sed -n 's/^pr: *\([^ #]*\).*/\1/p' "$f" | head -1)
    merged=$(sed -n 's/^merged: *\([^ #]*\).*/\1/p' "$f" | head -1)
    title=$(sed -n 's/^# \(.*\)/\1/p' "$f" | head -1)
    echo "| ${id:--} | ${title:-?} | ${status:-?} | ${spec:--} | ${pr:--} | ${merged:--} | \`$f\` |"
  done | sort
} > INDEX.md
echo "INDEX.md rebuilt."
